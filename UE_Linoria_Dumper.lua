--[[
    Unnamed API Custom Dumper Addon (Linoria UI)
]]

-- The 'api' object is directly injected into the environment by Unnamed.
local UnnamedAPI = api

if not UnnamedAPI then
    warn("[UI Dumper] Warning: 'api' not found in environment.")
end

if UnnamedAPI and UnnamedAPI.set_lua_name then
    UnnamedAPI:set_lua_name("ui_dumper")
end

local tabs = {
    Dumper = UnnamedAPI:AddTab("Dumper")
}

local main_groupbox = tabs.Dumper:AddLeftGroupbox("Custom Linoria Dumpers")
local spec_groupbox = tabs.Dumper:AddRightGroupbox("API Object Dumper")

main_groupbox:AddLabel("These utilize native Linoria UI globals.")

local function dump_toggles()
    if not getgenv().Toggles then 
        if UnnamedAPI then UnnamedAPI:notify("Toggles global missing.") end
        return 
    end
    local out = "-- Toggles Dump --\n\n"
    for name, toggle in pairs(getgenv().Toggles) do
        out = out .. string.format("%s = %s\n", tostring(name), tostring(toggle.Value))
    end
    if writefile then
        writefile("Unnamed_Toggles_Dump.txt", out)
        if UnnamedAPI then UnnamedAPI:notify("Dumped Toggles to workspace!", 3) end
    end
end

local function dump_options()
    if not getgenv().Options then 
        if UnnamedAPI then UnnamedAPI:notify("Options global missing.") end
        return 
    end
    local out = "-- Options Dump --\n\n"
    for name, opt in pairs(getgenv().Options) do
        local val = opt.Value
        if typeof(val) == "Color3" then
            val = tostring(val)
        elseif type(val) == "table" then
            local t = {}
            for k,v in pairs(val) do 
                if v == true then table.insert(t, tostring(k)) end
            end
            val = "{" .. table.concat(t, ", ") .. "}"
        end
        out = out .. string.format("%s = %s\n", tostring(name), tostring(val))
    end
    if writefile then
        writefile("Unnamed_Options_Dump.txt", out)
        if UnnamedAPI then UnnamedAPI:notify("Dumped Options to workspace!", 3) end
    end
end

main_groupbox:AddButton({
    Text = 'Dump Toggles (Native)',
    Func = dump_toggles,
    DoubleClick = false,
    Tooltip = 'Dumps all Toggles from the global Linoria Toggles table.'
})

main_groupbox:AddButton({
    Text = 'Dump Options (Native)',
    Func = dump_options,
    DoubleClick = false,
    Tooltip = 'Dumps all Options (Sliders, Dropdowns, ColorPickers) from the global Linoria Options table.'
})

spec_groupbox:AddLabel("Dumps known UI flags from Unnamed docs.")

local function dump_api_flags()
    local out = "-- Unnamed API Flags Dump --\n\n"
    local dumped_count = 0
    for _, flag in ipairs(flag_list) do
        local success, obj = pcall(function() return UnnamedAPI:get_ui_object(flag) end)
        if success and type(obj) == "table" then
            local has_val, val = pcall(function() return obj:GetValue() end)
            if not has_val then
                has_val, val = pcall(function() return obj.Value end)
            end
            if has_val then
                if typeof(val) == "Color3" then val = tostring(val) end
                if type(val) == "table" then
                    local t = {}
                    for k,v in pairs(val) do 
                        if v == true then table.insert(t, tostring(k)) end
                    end
                    val = "{" .. table.concat(t, ", ") .. "}"
                end
                out = out .. string.format("%s = %s\n", flag, tostring(val))
                dumped_count = dumped_count + 1
            else
                out = out .. string.format("%s = [Object Found, but cannot read value]\n", flag)
            end
        end
    end
    if writefile then
        writefile("Unnamed_API_Flags_Dump.txt", out)
        if UnnamedAPI then UnnamedAPI:notify("Dumped " .. tostring(dumped_count) .. " flags to workspace!", 4) end
    else
        if UnnamedAPI then UnnamedAPI:notify("Your executor does not support writefile!", 4) end
    end
end

spec_groupbox:AddButton({
    Text = 'Dump Documented Flags',
    Func = dump_api_flags,
    DoubleClick = false,
    Tooltip = 'Iterates over all documented Unnamed flags and fetches them using api:get_ui_object().'
})

if UnnamedAPI and UnnamedAPI.on_event then
    UnnamedAPI:on_event("unload", function()
        UnnamedAPI:notify("UI Custom Dumper unloaded.", 2)
    end)
end

if UnnamedAPI and UnnamedAPI.notify then
    UnnamedAPI:notify("Loaded Custom UE Dumper Addon!", 4)
end
